-- MindMap production schema. All tables are private; the Express API accesses
-- them through a server-only PostgreSQL connection string.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student','admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS subjects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE, name TEXT NOT NULL, semester INTEGER NOT NULL,
  description TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  number INTEGER NOT NULL, title TEXT NOT NULL, UNIQUE(subject_id,number)
);
CREATE TABLE IF NOT EXISTS topics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
  title TEXT NOT NULL, position INTEGER NOT NULL DEFAULT 0, UNIQUE(unit_id,title)
);
CREATE TABLE IF NOT EXISTS coverage (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  studied SMALLINT NOT NULL CHECK(studied IN (0,1)), note TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,topic_id)
);
CREATE TABLE IF NOT EXISTS coverage_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  studied SMALLINT NOT NULL CHECK(studied IN (0,1)), note TEXT NOT NULL DEFAULT '',
  changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id BIGINT NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  text TEXT NOT NULL, type TEXT NOT NULL CHECK(type IN ('mcq','multiple_select','true_false','short_answer')),
  options TEXT NOT NULL DEFAULT '[]', correct_answer TEXT NOT NULL, explanation TEXT NOT NULL DEFAULT '',
  difficulty TEXT NOT NULL DEFAULT 'medium' CHECK(difficulty IN ('easy','medium','hard')),
  marks REAL NOT NULL DEFAULT 1 CHECK(marks > 0), is_demo SMALLINT NOT NULL DEFAULT 0 CHECK(is_demo IN (0,1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  subject_id BIGINT NOT NULL REFERENCES subjects(id), started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ, question_count INTEGER NOT NULL DEFAULT 0,
  earned REAL NOT NULL DEFAULT 0, possible REAL NOT NULL DEFAULT 0, accuracy REAL NOT NULL DEFAULT 0,
  attempted_count INTEGER NOT NULL DEFAULT 0, correct_count INTEGER NOT NULL DEFAULT 0,
  incorrect_count INTEGER NOT NULL DEFAULT 0, unanswered_count INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS assessment_questions (
  assessment_id BIGINT NOT NULL REFERENCES assessments(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES questions(id), position INTEGER NOT NULL,
  marked_for_review SMALLINT NOT NULL DEFAULT 0,
  PRIMARY KEY(assessment_id,question_id)
);
CREATE TABLE IF NOT EXISTS answers (
  assessment_id BIGINT NOT NULL REFERENCES assessments(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL REFERENCES questions(id), answer TEXT,
  correct SMALLINT NOT NULL CHECK(correct IN (0,1)), earned REAL NOT NULL DEFAULT 0,
  PRIMARY KEY(assessment_id,question_id)
);
CREATE TABLE IF NOT EXISTS resources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
  title TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('video','documentation','website','notes','practice','book','pdf','image','video_file','youtube','external_link','notes_file','reference','practice_file')),
  url TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', verified SMALLINT NOT NULL DEFAULT 0 CHECK(verified IN (0,1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resource_type TEXT NOT NULL DEFAULT 'link', visibility TEXT NOT NULL DEFAULT 'published',
  publication_status TEXT NOT NULL DEFAULT 'published', file_key TEXT, original_filename TEXT,
  mime_type TEXT, file_size BIGINT, thumbnail_key TEXT, tags TEXT NOT NULL DEFAULT '[]',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS recommendations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES topics(id) ON DELETE CASCADE, reason TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admin_activity (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action TEXT NOT NULL, entity_type TEXT NOT NULL, entity_id BIGINT,
  details TEXT NOT NULL DEFAULT '{}', created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS assessment_topic_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES assessments(id) ON DELETE CASCADE,
  topic_id BIGINT NOT NULL REFERENCES topics(id), question_count INTEGER NOT NULL,
  attempted_count INTEGER NOT NULL, correct_count INTEGER NOT NULL,
  earned REAL NOT NULL, possible REAL NOT NULL, accuracy REAL NOT NULL,
  UNIQUE(assessment_id,topic_id)
);
CREATE TABLE IF NOT EXISTS mindmap_sessions (
  sid TEXT PRIMARY KEY, sess JSONB NOT NULL, expire TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_questions_topic ON questions(topic_id);
CREATE INDEX IF NOT EXISTS idx_assessments_user ON assessments(user_id,completed_at);
CREATE INDEX IF NOT EXISTS idx_coverage_user ON coverage(user_id,studied);
CREATE INDEX IF NOT EXISTS idx_resources_topic ON resources(topic_id);
CREATE INDEX IF NOT EXISTS idx_admin_activity_time ON admin_activity(created_at);
CREATE INDEX IF NOT EXISTS idx_mindmap_sessions_expire ON mindmap_sessions(expire);
CREATE INDEX IF NOT EXISTS idx_admin_activity_user ON admin_activity(admin_user_id);
CREATE INDEX IF NOT EXISTS idx_answers_question ON answers(question_id);
CREATE INDEX IF NOT EXISTS idx_assessment_questions_question ON assessment_questions(question_id);
CREATE INDEX IF NOT EXISTS idx_assessment_topic_results_topic ON assessment_topic_results(topic_id);
CREATE INDEX IF NOT EXISTS idx_assessments_subject ON assessments(subject_id);
CREATE INDEX IF NOT EXISTS idx_coverage_topic ON coverage(topic_id);
CREATE INDEX IF NOT EXISTS idx_coverage_history_topic ON coverage_history(topic_id);
CREATE INDEX IF NOT EXISTS idx_coverage_history_user ON coverage_history(user_id);
CREATE INDEX IF NOT EXISTS idx_questions_subject ON questions(subject_id);
CREATE INDEX IF NOT EXISTS idx_questions_unit ON questions(unit_id);
CREATE INDEX IF NOT EXISTS idx_recommendations_topic ON recommendations(topic_id);
CREATE INDEX IF NOT EXISTS idx_recommendations_user ON recommendations(user_id);
